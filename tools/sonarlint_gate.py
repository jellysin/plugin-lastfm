"""Generate and check the root SonarLint.xml that Codacy's SonarC# tool reads.

Codacy uses configuration-file mode: it reads rule keys from the root SonarLint.xml
and runs every Sonar analyzer when that file is missing. Change the saved rules in
.config/codacy/sonar-csharp.json, or rebuild that snapshot with --from-api from saved
Codacy API v3 pages, then run --write. This offline gate cannot see Codacy UI changes;
refresh the snapshot after changing enabled patterns there.
"""

import argparse
from datetime import date
import difflib
import html
import json
from pathlib import Path
import re
import sys

from semgrep_gate import GateError, MARK, read_bounded

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / ".config" / "codacy" / "sonar-csharp.json"
TARGET = ROOT / "SonarLint.xml"
TOOL_UUID = "8954dff3-f19c-429c-ac76-c45fa5e73b62"
MAX_SNAPSHOT_BYTES = 256 * 1024
MAX_XML_BYTES = 512 * 1024
MAX_PAGE_BYTES = 4 * 1024 * 1024
MAX_PAGES = 20
MAX_RULES = 2000
MAX_PRINTED = 200
GENERATED_COMMENT = (
    "Generated by tools/sonarlint_gate.py from .config/codacy/sonar-csharp.json. "
    "Do not edit; see CONTRIBUTING.md."
)
PLANTED_CASES = 8
# CR is left out because XML parsers turn it into LF.
XML_VALUE = re.compile(r"[\t\n\x20-\ud7ff\ue000-\ufffd\U00010000-\U0010ffff]*")


def plain_int(value) -> bool:
    """Return whether a value is an integer other than a boolean."""
    return isinstance(value, int) and not isinstance(value, bool)


def json_object(text: str, source: str) -> dict:
    """Decode a JSON object, reporting malformed input as a gate error."""
    try:
        value = json.loads(text)
    except ValueError as error:
        raise GateError(f"{source}: invalid JSON: {error}") from error
    if not isinstance(value, dict):
        raise GateError(f"{source}: expected a JSON object")
    return value


def parameters(key: str, raw: list, *, sort: bool = False) -> list[tuple[str, str]]:
    """Validate parameter names and values, optionally sorting saved API data."""
    if not isinstance(raw, list):
        raise GateError(f"{key}: parameters must be a list")
    result = []
    seen = set()
    for item in raw:
        if not isinstance(item, dict):
            raise GateError(f"{key}: parameter must be an object")
        name, value = item.get("name"), item.get("value")
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name):
            raise GateError(f"{key}: invalid parameter name {name!r}")
        if not isinstance(value, str):
            raise GateError(f"{key}: parameter {name} value must be a string")
        if not XML_VALUE.fullmatch(value):
            raise GateError(f"{key}: parameter {name} value has a character XML 1.0 cannot carry unchanged")
        if name in seen or (not sort and result and name <= result[-1][0]):
            raise GateError(f"{key}: parameter {name} is duplicated or out of order")
        seen.add(name)
        result.append((name, value))
    return sorted(result) if sort else result


def load_snapshot(text: str) -> list[tuple[str, list[tuple[str, str]]]]:
    """Return nonempty, bounded, numerically ordered rule keys and sorted parameters."""
    raw = json_object(text, "snapshot").get("rules")
    if not isinstance(raw, list) or not 1 <= len(raw) <= MAX_RULES:
        raise GateError(f"rules: expected between 1 and {MAX_RULES} rules")
    result = []
    seen = set()
    previous = -1
    for rule in raw:
        if not isinstance(rule, dict):
            raise GateError(f"rule {rule!r}: expected an object")
        key = rule.get("key")
        if not isinstance(key, str) or not re.fullmatch(r"S[0-9]+", key):
            raise GateError(f"{key!r}: invalid rule key; expected S followed by digits")
        try:
            number = int(key[1:])
        except ValueError as error:
            raise GateError(f"{key}: invalid numeric rule key") from error
        if key in seen or number <= previous:
            raise GateError(f"{key}: duplicate rule key or nonascending numeric order")
        result.append((key, parameters(key, rule.get("parameters", []))))
        seen.add(key)
        previous = number
    return result


def render(rules) -> str:
    """Render analyzer input with stable whitespace, XML escaping and a final newline."""
    if "--" in GENERATED_COMMENT:
        raise GateError("generated XML comment must not contain --")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>', f"<!-- {GENERATED_COMMENT} -->",
        "<AnalysisInput>", "  <Rules>",
    ]
    for key, values in rules:
        lines.extend(["    <Rule>", f"      <Key>{html.escape(key, quote=False)}</Key>"])
        if values:
            lines.append("      <Parameters>")
            for name, value in values:
                lines.extend([
                    "        <Parameter>", f"          <Key>{html.escape(name, quote=False)}</Key>",
                    f"          <Value>{html.escape(value, quote=False)}</Value>", "        </Parameter>",
                ])
            lines.append("      </Parameters>")
        else:
            lines.append("      <Parameters />")
        lines.append("    </Rule>")
    return "\n".join([*lines, "  </Rules>", "</AnalysisInput>", ""])


def drift(expected: str, actual: str) -> list[str]:
    """Return a bounded unified diff when the generated and actual text differ."""
    if expected == actual:
        return []
    lines = [line.removesuffix("\n") for line in difflib.unified_diff(
        expected.splitlines(keepends=True), actual.splitlines(keepends=True),
        fromfile="rendered from snapshot", tofile="SonarLint.xml", lineterm="",
    )]
    if len(lines) > MAX_PRINTED:
        return [*lines[:MAX_PRINTED], f"... {len(lines) - MAX_PRINTED} more diff lines"]
    return lines


def check(snapshot: Path, target: Path) -> list[str]:
    """Compare bounded UTF-8 files and explain when the root configuration is absent."""
    expected = render(load_snapshot(read_bounded(snapshot, MAX_SNAPSHOT_BYTES)))
    try:
        actual = read_bounded(target, MAX_XML_BYTES)
    except FileNotFoundError as error:
        raise GateError("SonarLint.xml is missing") from error
    return drift(expected, actual)


def api_items(texts: list[str]) -> list[dict]:
    """Collect bounded saved pages and verify every declared total against all items."""
    if not 1 <= len(texts) <= MAX_PAGES:
        raise GateError(f"API: expected between 1 and {MAX_PAGES} pages")
    items, totals = [], []
    for index, text in enumerate(texts, start=1):
        if len(text.encode("utf-8")) > MAX_PAGE_BYTES:
            raise GateError(f"API page {index}: exceeds {MAX_PAGE_BYTES} bytes")
        page = json_object(text, f"API page {index}")
        data, pagination = page.get("data"), page.get("pagination")
        if not isinstance(data, list) or not isinstance(pagination, dict):
            raise GateError(f"API page {index}: expected data list and pagination object")
        total = pagination.get("total")
        if not plain_int(total) or not 1 <= total <= MAX_RULES:
            raise GateError(f"API page {index}: invalid pagination.total")
        if len(items) + len(data) > MAX_RULES:
            raise GateError(f"API: more than {MAX_RULES} rules")
        items.extend(data)
        totals.append(total)
    if not items or any(total != len(items) for total in totals):
        raise GateError("API: collected item count differs from pagination.total")
    return items


def api_rule(item: dict, standard: list) -> dict:
    """Validate one enabled SonarC# item and normalize its parameters."""
    if not isinstance(item, dict):
        raise GateError("API rule: expected an object")
    definition = item.get("patternDefinition")
    identifier = definition.get("id") if isinstance(definition, dict) else None
    match = re.fullmatch(r"SonarCSharp_(S[0-9]+)", identifier) if isinstance(identifier, str) else None
    if match is None:
        raise GateError(f"{identifier!r}: invalid SonarC# pattern id")
    key = match.group(1)
    if item.get("enabled") is not True:
        raise GateError(f"{key}: API item must be enabled")
    if item.get("enabledBy") != standard:
        raise GateError(f"{key}: enabledBy differs from the first item's coding standard")
    values = parameters(key, item.get("parameters", []), sort=True)
    return {"key": key, "parameters": [{"name": name, "value": value} for name, value in values]}


def snapshot_from_pages(texts: list[str], read_date: str) -> str:
    """Rebuild a canonical snapshot from complete saved enabled-pattern API pages."""
    try:
        date.fromisoformat(read_date)
    except (TypeError, ValueError) as error:
        raise GateError(f"read date {read_date!r}: expected an ISO calendar date") from error
    items = api_items(texts)
    standard = items[0].get("enabledBy") if isinstance(items[0], dict) else None
    if not isinstance(standard, list) or len(standard) != 1 or not isinstance(standard[0], dict):
        raise GateError("API: enabledBy must contain exactly one coding standard")
    identity = standard[0]
    if not plain_int(identity.get("id")) or not isinstance(identity.get("name"), str):
        raise GateError("API: coding standard requires an integer id and string name")
    rules = [api_rule(item, standard) for item in items]
    try:
        rules.sort(key=rule_number)
    except ValueError as error:
        raise GateError("API: invalid numeric rule key") from error
    data = {
        "tool": "SonarC#", "toolUuid": TOOL_UUID,
        "source": "Codacy API v3 repository tool patterns of jellysin/plugin-lastfm, enabled patterns only",
        "codingStandard": {"id": identity["id"], "name": identity["name"]},
        "readDate": read_date, "rules": rules,
    }
    result = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    load_snapshot(result)
    return result


def rule_number(rule: dict) -> int:
    """Return the numeric suffix used to sort an API rule."""
    return int(rule["key"][1:])


def rejects(function, *arguments) -> bool:
    """Return whether the gate rejects a planted invalid input."""
    try:
        function(*arguments)
    except GateError:
        return True
    return False


def self_test() -> list[str]:
    """Exercise valid generation and eight planted drift or validation failures in memory."""
    rules = [
        {"key": "S110", "parameters": [
            {"name": "filteredClasses", "value": ""}, {"name": "max", "value": "5"},
        ]},
        {"key": "S112", "parameters": []},
    ]
    rendered = render(load_snapshot(json.dumps({"rules": rules})))
    failures = []
    if drift(rendered, rendered) or "<Value></Value>" not in rendered or "<Parameters />" not in rendered:
        failures.append("valid two-rule snapshot did not render and match")
    extra = render([("S1451", [])]).split("  <Rules>\n")[1].split("  </Rules>")[0]
    variants = [
        rendered.replace("  </Rules>", extra + "  </Rules>"), render([("S112", [])]),
        rendered.replace("<Value>5</Value>", "<Value>6</Value>"),
    ]
    for label, actual in zip(("extra S1451", "removed S110", "changed max"), variants, strict=True):
        if not drift(rendered, actual):
            failures.append(f"{MARK} {label} not detected")
    bad_rules = [
        [rules[0], rules[0]], [{"key": "SonarCSharp_S112", "parameters": []}], list(reversed(rules)),
    ]
    for label, invalid in zip(("duplicate key", "prefixed key", "descending order"), bad_rules, strict=True):
        if not rejects(load_snapshot, json.dumps({"rules": invalid})):
            failures.append(f"{MARK} {label} not detected")
    for enabled, total in ((False, 1), (True, 2)):
        page = {"data": [{
            "patternDefinition": {"id": "SonarCSharp_S112"}, "enabled": enabled, "parameters": [],
            "enabledBy": [{"id": 172687, "name": "Default coding standard"}],
        }], "pagination": {"total": total}}
        if not rejects(snapshot_from_pages, [json.dumps(page)], "2026-11-10"):
            failures.append(f"{MARK} enabled={enabled}, total={total} not detected")
    return failures


def run_arguments(arguments) -> int:
    """Execute the selected offline operation without starting any subprocess."""
    if arguments.self_test:
        failures = self_test()
        for failure in failures:
            print(f"sonarlint self-test: {failure}", file=sys.stderr)
        if not failures:
            print(f"sonarlint self-test: {PLANTED_CASES} planted cases detected")
        return 1 if failures else 0
    if arguments.from_api:
        if len(arguments.from_api) > MAX_PAGES:
            raise GateError(f"API: more than {MAX_PAGES} pages")
        texts = [read_bounded(path, MAX_PAGE_BYTES) for path in arguments.from_api]
        arguments.output.write_text(snapshot_from_pages(texts, arguments.read_date), encoding="utf-8", newline="\n")
        return 0
    if arguments.write:
        TARGET.write_text(render(load_snapshot(read_bounded(SNAPSHOT, MAX_SNAPSHOT_BYTES))),
                          encoding="utf-8", newline="\n")
        return 0
    lines = check(SNAPSHOT, TARGET)
    if lines:
        for line in lines:
            print(line)
        print("SonarLint.xml differs from .config/codacy/sonar-csharp.json; "
              "regenerate with: python3 tools/sonarlint_gate.py --write")
        return 1
    count = len(load_snapshot(read_bounded(SNAPSHOT, MAX_SNAPSHOT_BYTES)))
    print(f"sonarlint: SonarLint.xml matches {count} rules")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Generate XML, import saved API pages, self-test or check for drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--write", action="store_true", help="regenerate the root SonarLint.xml")
    modes.add_argument("--self-test", action="store_true", help="check in-memory planted cases")
    modes.add_argument("--from-api", nargs="+", type=Path, metavar="PAGE", help="import saved Codacy API pages")
    parser.add_argument("--read-date", metavar="YYYY-MM-DD", help="date the API pages were read; required for --from-api")
    parser.add_argument("--output", type=Path, default=SNAPSHOT, help="snapshot output path for --from-api")
    arguments = parser.parse_args(argv)
    if arguments.from_api and arguments.read_date is None:
        parser.error("--from-api requires --read-date YYYY-MM-DD")
    try:
        return run_arguments(arguments)
    except (GateError, OSError, UnicodeError) as error:
        print(f"sonarlint: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
