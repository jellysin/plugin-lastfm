"""No commit message and no pull request text credits a model or coding tool; people and bots keep their lines."""

import contextlib
import io
import json
import subprocess
import tempfile
import unittest
from pathlib import Path

from tools.attribution import MAX_EVENT_BYTES, AttributionError, check, credits_tool, event_texts, history, main, scan

MODEL = "Co-authored-by: Claude Opus 5.5 <noreply@anthropic.com>"
FOOTER = "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)"
IDENTITY = ("-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false")


def run(arguments):
    output, errors = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(output), contextlib.redirect_stderr(errors):
        code = main(arguments)
    return code, output.getvalue(), errors.getvalue()


def git(directory, *arguments):
    subprocess.run(["git", "-C", str(directory), *arguments], check=True, capture_output=True)


class LineTests(unittest.TestCase):
    def test_trailer_for_a_model_or_coding_tool_is_refused(self):
        refused = (
            MODEL,
            "co-authored-by:Claude <noreply@anthropic.com>",
            "  Co-Authored-By: Claude Opus 4.7 (1M context) <noreply@anthropic.com>",
            "Co-authored-by: Somebody Else <noreply@anthropic.com>",
            "Co-authored-by: Claude <claude@example.org>",
            "Co-authored-by: Codex <codex@example.invalid>",
            "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
            "Co-authored-by: Cursor Agent <agent@example.invalid>",
            "Co-authored-by: aider (gpt-4o) <aider@example.invalid>",
            "Assisted-by: GitHub Copilot",
            "Generated-by: Gemini 3 Pro",
            "Co-developed-by: Devin AI <devin@example.invalid>",
        )
        for line in refused:
            with self.subTest(line=line):
                self.assertTrue(credits_tool(line))

    def test_footer_for_a_coding_tool_is_refused(self):
        for line in (FOOTER, "Generated with [Claude Code](https://claude.com/claude-code)", "Generated by Cursor", "_Written with Codex CLI._", "Created using **GitHub Copilot** - review carefully", "Generated with Claude."):
            with self.subTest(line=line):
                self.assertTrue(credits_tool(line))

    def test_people_and_bots_keep_their_trailers(self):
        kept = (
            "Co-authored-by: renovate[bot] <29139614+renovate[bot]@users.noreply.github.com>",
            "Co-authored-by: github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>",
            "Co-authored-by: Kilian <kilian@example.org>",
            "Co-authored-by: Claude Dupont <claude@example.org>",
            "Co-authored-by: Devin Example <devin@example.org>",
            "Signed-off-by: Jules Cursor <jules@example.org>",
            "Reviewed-by: Jane <jane@anthropic.example.org>",
        )
        for line in kept:
            with self.subTest(line=line):
                self.assertFalse(credits_tool(line))

    def test_release_tooling_footers_and_prose_pass(self):
        kept = (
            "This PR was generated with [Release Please](https://github.com/googleapis/release-please). See [documentation](https://github.com/googleapis/release-please#release-please).",
            "This PR has been generated by [Mend Renovate](https://mend.io/renovate/).",
            "Generated with [Release Please](https://github.com/googleapis/release-please)",
            "docs: describe how Claude Code hooks are configured",
            "chore: ignore the files generated by Copilot",
            "Generated by the build from web/account.ts",
            "Created by Claude Dupont in 2019.",
            "",
        )
        for line in kept:
            with self.subTest(line=line):
                self.assertFalse(credits_tool(line))

    def test_findings_carry_the_source_and_the_line_number(self):
        found = scan("commit 0123456789ab", f"fix: a change\n\nBody text.\n\n{FOOTER}\n\n{MODEL}\n")
        self.assertEqual([("commit 0123456789ab", 5, FOOTER), ("commit 0123456789ab", 7, MODEL)], [(item.source, item.number, item.line) for item in found])


class HistoryTests(unittest.TestCase):
    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.root = Path(scratch.name)
        self.repository = self.root / "repository"
        self.repository.mkdir()
        git(self.repository, "init", "--quiet", "--initial-branch=main")

    def commit(self, message):
        git(self.repository, *IDENTITY, "commit", "--quiet", "--allow-empty", "--no-verify", "-m", message)

    def test_every_reachable_message_is_read(self):
        self.commit("feat: first\n\nCo-authored-by: Kilian <kilian@example.org>")
        self.commit("fix: second")
        self.assertEqual(["fix: second\n", "feat: first\n\nCo-authored-by: Kilian <kilian@example.org>\n"], [message for _, message in history(self.repository, "HEAD")])
        self.assertEqual((2, 0, []), check(self.repository, "HEAD", None))

    def test_planted_trailer_in_an_older_commit_is_reported_with_its_commit(self):
        self.commit(f"feat: first\n\n{MODEL}")
        self.commit("fix: second")
        planted = subprocess.run(["git", "-C", str(self.repository), "rev-parse", "HEAD~1"], check=True, capture_output=True, text=True).stdout.strip()
        count, _, found = check(self.repository, "HEAD", None)
        self.assertEqual((2, [(f"commit {planted[:12]}", 3, MODEL)]), (count, [(item.source, item.number, item.line) for item in found]))
        code, output, errors = run(["--repository", str(self.repository)])
        self.assertEqual((1, ""), (code, output))
        self.assertIn(f"commit {planted[:12]}, line 3: {MODEL}", errors)

    def test_shallow_clone_is_refused_instead_of_passing_on_its_last_commit(self):
        self.commit(f"feat: first\n\n{MODEL}")
        self.commit("fix: second")
        shallow = self.root / "shallow"
        git(self.root, "clone", "--quiet", "--depth=1", self.repository.as_uri(), str(shallow))
        with self.assertRaisesRegex(AttributionError, "shallow"):
            history(shallow, "HEAD")
        self.assertEqual(2, run(["--repository", str(shallow)])[0])

    def test_unreadable_history_is_refused(self):
        with self.assertRaisesRegex(AttributionError, "git log failed"):
            history(self.repository, "HEAD")
        self.commit("feat: first")
        for revision in ("no-such-branch", "--all"):
            with self.subTest(revision=revision), self.assertRaises(AttributionError):
                history(self.repository, revision)
        self.assertEqual(2, run(["--repository", str(self.root / "absent")])[0])


class EventTests(unittest.TestCase):
    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.root = Path(scratch.name)
        self.repository = self.root / "repository"
        self.repository.mkdir()
        git(self.repository, "init", "--quiet")
        git(self.repository, *IDENTITY, "commit", "--quiet", "--allow-empty", "-m", "feat: first")

    def event(self, content):
        path = self.root / "event.json"
        path.write_text(content if isinstance(content, str) else json.dumps(content), encoding="utf-8")
        return path

    def test_title_and_text_of_a_pull_request_are_checked(self):
        clean = self.event({"pull_request": {"title": "fix: a change", "body": "## Change\n\nText.\n"}})
        self.assertEqual([("pull request title", "fix: a change"), ("pull request text", "## Change\n\nText.\n")], event_texts(clean))
        code, output, _ = run(["--repository", str(self.repository), "--event", str(clean)])
        self.assertEqual((0, "Attribution check: 1 commit message(s) and 2 pull request text(s) credit no model or coding tool\n"), (code, output))
        planted = self.event({"pull_request": {"title": "fix: a change", "body": f"## Change\n\nText.\n\n{FOOTER}\n"}})
        code, _, errors = run(["--repository", str(self.repository), "--event", str(planted)])
        self.assertEqual(1, code)
        self.assertIn(f"pull request text, line 5: {FOOTER}", errors)

    def test_empty_text_and_other_events_carry_nothing_to_refuse(self):
        self.assertEqual([("pull request title", "fix: a change"), ("pull request text", "")], event_texts(self.event({"pull_request": {"title": "fix: a change", "body": None}})))
        self.assertEqual([], event_texts(self.event({"ref": "refs/heads/main", "head_commit": {"message": "x"}})))

    def test_unreadable_event_is_refused(self):
        for content in ("{ not json", "[]", {"pull_request": "text"}, {"pull_request": {"body": "text"}}, {"pull_request": {"title": "t", "body": 7}}, "x" * (MAX_EVENT_BYTES + 1)):
            with self.subTest(content=str(content)[:24]):
                self.assertEqual(2, run(["--repository", str(self.repository), "--event", str(self.event(content))])[0])
        self.assertEqual(2, run(["--repository", str(self.repository), "--event", str(self.root / "absent.json")])[0])


class SelfTestTests(unittest.TestCase):
    def test_self_test_passes_and_fails_when_a_rule_is_removed(self):
        self.assertEqual((0, "Attribution self-test: 13 cases behaved as required\n"), run(["--self-test"])[:2])
        import tools.attribution as attribution
        from unittest.mock import patch
        with patch.object(attribution, "credits_tool", return_value=False):
            code, _, errors = run(["--self-test"])
        self.assertEqual(2, code)
        self.assertIn("should be refused", errors)


