"""The root SonarLint configuration follows the saved Codacy rules without drift."""

import contextlib
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import sonarlint_gate  # noqa: E402 - module imported after sys.path manipulation

RULES = [
    {"key": "S110", "parameters": [
        {"name": "filteredClasses", "value": ""}, {"name": "max", "value": "5"},
    ]},
    {"key": "S112", "parameters": []},
]
STANDARD = [{"id": 172687, "name": "Default coding standard"}]
EXPECTED_XML = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/sonarlint_gate.py from .config/codacy/sonar-csharp.json. Do not edit; see CONTRIBUTING.md. -->
<AnalysisInput>
  <Rules>
    <Rule>
      <Key>S110</Key>
      <Parameters>
        <Parameter>
          <Key>filteredClasses</Key>
          <Value></Value>
        </Parameter>
        <Parameter>
          <Key>max</Key>
          <Value>5</Value>
        </Parameter>
      </Parameters>
    </Rule>
    <Rule>
      <Key>S112</Key>
      <Parameters />
    </Rule>
  </Rules>
</AnalysisInput>
'''


def snapshot(rules=None):
    """Return an isolated synthetic snapshot with the given rules."""
    return json.dumps({"rules": RULES if rules is None else rules})


def pages():
    """Return two Codacy pages with reversed rule and parameter order."""
    items = [
        {"patternDefinition": {"id": "SonarCSharp_" + rule["key"]},
         "enabled": True, "isCustom": False,
         "parameters": list(reversed(rule["parameters"])), "enabledBy": STANDARD}
        for rule in reversed(RULES)
    ]
    return [
        {"data": [items[0]], "pagination": {"cursor": "2", "limit": 1, "total": 2}},
        {"data": [items[1]], "pagination": {"limit": 1, "total": 2}},
    ]


def from_pages(data, read_date="2026-11-10"):
    """Convert synthetic API pages using the public importer."""
    return sonarlint_gate.snapshot_from_pages([json.dumps(page) for page in data], read_date)


class RenderTests(unittest.TestCase):
    """Rendering preserves the exact root-file layout and escapes XML text."""

    def test_committed_xml_matches_snapshot(self):
        """The generated root file agrees with all committed Codacy rules."""
        self.assertEqual(sonarlint_gate.check(sonarlint_gate.SNAPSHOT, sonarlint_gate.TARGET), [])

    def test_render_is_deterministic(self):
        """Two renders have identical bytes, indentation and final newline."""
        rules = sonarlint_gate.load_snapshot(snapshot())
        self.assertEqual(sonarlint_gate.render(rules), EXPECTED_XML)
        self.assertEqual(sonarlint_gate.render(rules), sonarlint_gate.render(rules))

    def test_without_parameters(self):
        """A rule without parameters uses the empty Parameters element."""
        self.assertIn("      <Parameters />\n", sonarlint_gate.render([("S112", [])]))

    def test_empty_value(self):
        """An empty parameter value has explicit start and end tags."""
        self.assertIn("<Value></Value>", sonarlint_gate.render([("S110", [("filteredClasses", "")])]))

    def test_xml_escaping(self):
        """Parameter text escapes ampersands and angle brackets."""
        self.assertIn("<Value>a&amp;b&lt;c&gt;</Value>",
                      sonarlint_gate.render([("S110", [("max", "a&b<c>")])]))

    def test_illegal_comment(self):
        """A double hyphen in the generated comment is refused before rendering."""
        with mock.patch.object(sonarlint_gate, "GENERATED_COMMENT", "invalid -- comment"):
            with self.assertRaises(sonarlint_gate.GateError):
                sonarlint_gate.render([("S112", [])])


class DriftTests(unittest.TestCase):
    """Extra rules, absent rules and changed parameters fail the comparison."""

    def test_identical_text(self):
        """The same XML text has no drift."""
        self.assertEqual(sonarlint_gate.drift(EXPECTED_XML, EXPECTED_XML), [])

    def test_extra_rule(self):
        """A planted unselected rule appears as an addition in the diff."""
        extra = "    <Rule>\n      <Key>S1451</Key>\n      <Parameters />\n    </Rule>\n"
        actual = EXPECTED_XML.replace("  </Rules>", extra + "  </Rules>")
        self.assertIn("+      <Key>S1451</Key>", sonarlint_gate.drift(EXPECTED_XML, actual))

    def test_missing_rule(self):
        """Removing S110 produces a deletion in the diff."""
        actual = sonarlint_gate.render([("S112", [])])
        self.assertIn("-      <Key>S110</Key>", sonarlint_gate.drift(EXPECTED_XML, actual))

    def test_changed_parameter(self):
        """Changing max from five to six is reported with both values."""
        actual = EXPECTED_XML.replace("<Value>5</Value>", "<Value>6</Value>")
        lines = sonarlint_gate.drift(EXPECTED_XML, actual)
        self.assertIn("-          <Value>5</Value>", lines)
        self.assertIn("+          <Value>6</Value>", lines)
        self.assertEqual(lines[:2], ["--- rendered from snapshot", "+++ SonarLint.xml"])

    def test_diff_is_bounded(self):
        """Large diffs retain MAX_PRINTED lines and one exact omitted-line count."""
        lines = sonarlint_gate.drift("", "x\n" * 500)
        self.assertEqual(len(lines), sonarlint_gate.MAX_PRINTED + 1)
        self.assertEqual(lines[-1], "... 303 more diff lines")

    def test_missing_final_newline(self):
        """An absent final newline remains a difference despite identical line text."""
        self.assertTrue(sonarlint_gate.drift(EXPECTED_XML, EXPECTED_XML.removesuffix("\n")))

    def test_missing_target(self):
        """An absent root file raises the actionable missing-file diagnostic."""
        with tempfile.TemporaryDirectory(prefix="sonarlint-test-") as directory:
            with self.assertRaisesRegex(sonarlint_gate.GateError, "SonarLint.xml is missing"):
                sonarlint_gate.check(sonarlint_gate.SNAPSHOT, Path(directory) / "SonarLint.xml")


class SnapshotTests(unittest.TestCase):
    """Snapshot keys and parameters must be valid, unique and ordered."""

    def test_duplicate_rule(self):
        """A duplicate rule fails with its key in the diagnostic."""
        with self.assertRaisesRegex(sonarlint_gate.GateError, "S110"):
            sonarlint_gate.load_snapshot(snapshot([RULES[0], RULES[0]]))

    def test_bad_key(self):
        """Codacy-prefixed identifiers cannot leak into analyzer keys."""
        with self.assertRaisesRegex(sonarlint_gate.GateError, "SonarCSharp_S112"):
            sonarlint_gate.load_snapshot(snapshot([{"key": "SonarCSharp_S112", "parameters": []}]))

    def test_non_ascii_digits(self):
        """Only ASCII digits form a rule number, in the snapshot and in API pages."""
        with self.assertRaises(sonarlint_gate.GateError):
            sonarlint_gate.load_snapshot(snapshot([{"key": "S\u0661\u0661\u0660", "parameters": []}]))
        data = pages()
        data[0]["data"][0]["patternDefinition"]["id"] = "SonarCSharp_S\u0661\u0661\u0662"
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(data)

    def test_unsorted_rules(self):
        """Descending numeric rule keys are refused."""
        with self.assertRaisesRegex(sonarlint_gate.GateError, "S110"):
            sonarlint_gate.load_snapshot(snapshot(list(reversed(RULES))))

    def test_invalid_parameters(self):
        """Bad names, nonstring values, duplicate names and reversed names fail."""
        cases = [
            [{"name": "bad-name", "value": "5"}], [{"name": "max", "value": 5}],
            [{"name": "max", "value": "5"}] * 2, list(reversed(RULES[0]["parameters"])),
        ]
        for parameters in cases:
            with self.subTest(parameters=parameters), self.assertRaisesRegex(sonarlint_gate.GateError, "S110"):
                sonarlint_gate.load_snapshot(snapshot([{"key": "S110", "parameters": parameters}]))

    def test_empty_rules(self):
        """No enabled rules is an invalid snapshot."""
        with self.assertRaises(sonarlint_gate.GateError):
            sonarlint_gate.load_snapshot(snapshot([]))

    def test_too_many_rules(self):
        """One more than the scalar rule bound is refused."""
        rules = [{"key": f"S{number}", "parameters": []} for number in range(sonarlint_gate.MAX_RULES + 1)]
        with self.assertRaises(sonarlint_gate.GateError):
            sonarlint_gate.load_snapshot(snapshot(rules))

    def test_exact_rule_bound(self):
        """Exactly MAX_RULES valid rules are accepted."""
        rules = [{"key": f"S{number}", "parameters": []} for number in range(sonarlint_gate.MAX_RULES)]
        self.assertEqual(len(sonarlint_gate.load_snapshot(snapshot(rules))), sonarlint_gate.MAX_RULES)

    def test_invalid_json(self):
        """Malformed JSON is surfaced as a gate error."""
        with self.assertRaises(sonarlint_gate.GateError):
            sonarlint_gate.load_snapshot("{")


class ApiTests(unittest.TestCase):
    """Saved enabled-pattern pages produce the canonical snapshot, or fail closed."""

    def test_two_pages_produce_exact_json(self):
        """The importer orders metadata, rules and parameters deterministically."""
        expected = {
            "tool": "SonarC#", "toolUuid": "8954dff3-f19c-429c-ac76-c45fa5e73b62",
            "source": "Codacy API v3 repository tool patterns of jellysin/plugin-lastfm, enabled patterns only",
            "codingStandard": STANDARD[0], "readDate": "2026-11-10", "rules": RULES,
        }
        self.assertEqual(from_pages(pages()), json.dumps(expected, indent=2, ensure_ascii=False) + "\n")

    def test_disabled_rule(self):
        """An item not explicitly enabled is refused."""
        data = pages()
        data[0]["data"][0]["enabled"] = False
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(data)

    def test_total_mismatch(self):
        """Every page total must equal the collected item count."""
        data = pages()
        data[1]["pagination"]["total"] = 3
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(data)

    def test_different_standards(self):
        """Rules from two coding standards cannot be silently combined."""
        data = pages()
        data[1]["data"][0]["enabledBy"] = [{"id": 99, "name": "Different standard"}]
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(data)

    def test_multiple_standards(self):
        """Exactly one enabling standard is required for every rule."""
        data = pages()
        data[0]["data"][0]["enabledBy"] = STANDARD * 2
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(data)

    def test_bad_read_date(self):
        """An impossible calendar date fails before any snapshot is written."""
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages(pages(), "2026-02-30")

    def test_duplicate_api_key(self):
        """Repeating a page cannot silently duplicate a rule."""
        data = pages()
        with self.assertRaises(sonarlint_gate.GateError):
            from_pages([data[0], data[0]])

    def test_page_bound(self):
        """An empty page list or one over MAX_PAGES is refused."""
        for data in ([], pages()[:1] * (sonarlint_gate.MAX_PAGES + 1)):
            with self.subTest(count=len(data)), self.assertRaises(sonarlint_gate.GateError):
                from_pages(data)


class CommandTests(unittest.TestCase):
    """CLI operations fail on drift and write only their requested generated outputs."""

    def test_main_returns_one_on_drift(self):
        """The default command fails and prints an actionable regeneration command."""
        with tempfile.TemporaryDirectory(prefix="sonarlint-test-") as directory:
            target = Path(directory) / "SonarLint.xml"
            source = Path(directory) / "snapshot.json"
            source.write_text(snapshot(), encoding="utf-8")
            target.write_text(EXPECTED_XML.replace("<Value>5</Value>", "<Value>6</Value>"), encoding="utf-8")
            output = io.StringIO()
            with mock.patch.multiple(sonarlint_gate, TARGET=target, SNAPSHOT=source):
                with contextlib.redirect_stdout(output):
                    self.assertEqual(sonarlint_gate.main([]), 1)
            self.assertIn("python3 tools/sonarlint_gate.py --write", output.getvalue())

    def test_main_writes_then_checks(self):
        """Writing from a synthetic snapshot yields the exact checked XML."""
        with tempfile.TemporaryDirectory(prefix="sonarlint-test-") as directory:
            source = Path(directory) / "snapshot.json"
            target = Path(directory) / "SonarLint.xml"
            source.write_text(snapshot(), encoding="utf-8")
            with mock.patch.multiple(sonarlint_gate, TARGET=target, SNAPSHOT=source):
                with contextlib.redirect_stdout(io.StringIO()):
                    self.assertEqual(sonarlint_gate.main(["--write"]), 0)
                    self.assertEqual(sonarlint_gate.main([]), 0)
            self.assertEqual(target.read_bytes(), EXPECTED_XML.encode("utf-8"))

    def test_main_imports_saved_pages(self):
        """API import reads local pages and writes only the selected snapshot output."""
        with tempfile.TemporaryDirectory(prefix="sonarlint-test-") as directory:
            paths = [Path(directory) / f"page-{number}.json" for number in range(2)]
            for path, page in zip(paths, pages(), strict=True):
                path.write_text(json.dumps(page), encoding="utf-8")
            output = Path(directory) / "snapshot.json"
            self.assertEqual(sonarlint_gate.main([
                "--from-api", *map(str, paths), "--read-date", "2026-11-10", "--output", str(output),
            ]), 0)
            self.assertEqual(output.read_text(encoding="utf-8"), from_pages(pages()))

    def test_self_test(self):
        """All in-memory planted cases are detected."""
        self.assertEqual(sonarlint_gate.self_test(), [])

    def test_self_test_catches_disabled_drift(self):
        """A comparison that always passes must fail the planted self-test."""
        with mock.patch.object(sonarlint_gate, "drift", return_value=[]):
            self.assertEqual(len(sonarlint_gate.self_test()), 3)


if __name__ == "__main__":
    unittest.main()
